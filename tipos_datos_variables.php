<?php

// Tipos de datos y variables
// En PHP, las variables se definen con el símbolo de dólar ($) seguido del nombre de la variable.

// Tipos de datos comunes en PHP:
// 1. String: Cadena de texto
$name = 'Beto';

// 2. Integer: Número entero
$quantity = 14;

// 3. Float: Número decimal
$price = 9.99;

// 4. Boolean: Verdadero o falso
$paymentStatus = false;

// 5. null: Sin valor
$startDate = null;

var_dump($name);
var_dump($quantity);
var_dump($price);
var_dump($paymentStatus);
var_dump($startDate);

